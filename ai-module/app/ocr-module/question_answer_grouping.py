
from pathlib import Path
import json
import re
import argparse


# ============================================================
# CONFIGURATION
# ============================================================

DEFAULT_INPUT = Path("data/outputs/final_ocr_output.json")
DEFAULT_OUTPUT = Path("data/outputs/grouped_answers.json")


# ============================================================
# ANSWER HEADING DETECTION
# ============================================================

# Examples detected:
# Answer No. 01
# Answer no. -04
# Answer 02
# Answer-03
# Ans. 04
#
# Only explicit answer headings are detected.
# Ordinary question numbers are not treated as answer headings.

ANSWER_HEADING_PATTERN = re.compile(
    r"""
    ^[ \t]*
    (?:answer|ans)
    \s*
    (?:
        (?:no\.?|number)\s*
    )?
    [:\-#.]*
    \s*
    -?
    \s*
    (\d{1,2})
    \b
    [^\n]*
    """,
    re.IGNORECASE | re.MULTILINE | re.VERBOSE
)


# ============================================================
# INPUT / OUTPUT HELPERS
# ============================================================

def load_ocr_output(input_path):
    """Load page-wise OCR output generated by ocr_pipeline.py."""

    input_path = Path(input_path)

    if not input_path.exists():
        raise FileNotFoundError(
            f"OCR input file not found: {input_path}"
        )

    with open(input_path, "r", encoding="utf-8") as file:
        data = json.load(file)

    if not isinstance(data, list):
        raise ValueError(
            "Expected final_ocr_output.json to contain a list of pages."
        )

    return data


def save_json(data, output_path):
    """Save grouping results as JSON."""

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as file:
        json.dump(
            data,
            file,
            ensure_ascii=False,
            indent=4
        )


def normalize_answer_number(number):
    """Convert answer numbers to two-digit strings."""

    return str(int(number)).zfill(2)


# ============================================================
# ANSWER GROUPING
# ============================================================

def group_answers(page_results):
    """
    Group OCR text question-wise using explicit answer headings.

    Rules:
    1. An explicit answer heading starts a new answer.
    2. Text after a heading belongs to that answer.
    3. A page without a new heading continues the previous answer.
    4. Text before the first detected answer heading is unassigned.
    5. Multiple answers on one page are split separately.
    6. Original OCR text is preserved.
    """

    answers = {}
    unassigned_passages = []

    current_answer_number = None

    # Sort pages by page number to preserve exam order.
    page_results = sorted(
        page_results,
        key=lambda page: page.get("page_number", 0)
    )

    for page in page_results:

        page_number = page.get("page_number")
        page_name = page.get("page_name")
        page_text = page.get("text", "")

        if not isinstance(page_text, str):
            page_text = str(page_text or "")

        if not page_text.strip():
            continue

        print(f"\nProcessing page {page_number}...")

        headings = list(
            ANSWER_HEADING_PATTERN.finditer(page_text)
        )

        # ----------------------------------------------------
        # CASE 1: No answer heading on this page
        # ----------------------------------------------------

        if not headings:

            if current_answer_number is not None:

                print(
                    f"  Page {page_number}: "
                    f"continuation of Answer {current_answer_number}"
                )

                answers[current_answer_number]["segments"].append({
                    "page": page_number,
                    "page_name": page_name,
                    "text": page_text.strip(),
                    "type": "continuation"
                })

            else:

                print(
                    f"  Page {page_number}: "
                    "no answer heading and no previous answer"
                )

                unassigned_passages.append({
                    "page": page_number,
                    "page_name": page_name,
                    "text": page_text.strip(),
                    "status": "unassigned",
                    "reason": "No explicit answer heading found yet."
                })

            continue

        # ----------------------------------------------------
        # CASE 2: Text before the first heading
        # ----------------------------------------------------

        prefix = page_text[:headings[0].start()].strip()

        if prefix:

            if current_answer_number is not None:

                print(
                    f"  Page {page_number}: "
                    f"prefix continues Answer {current_answer_number}"
                )

                answers[current_answer_number]["segments"].append({
                    "page": page_number,
                    "page_name": page_name,
                    "text": prefix,
                    "type": "continuation"
                })

            else:

                unassigned_passages.append({
                    "page": page_number,
                    "page_name": page_name,
                    "text": prefix,
                    "status": "unassigned",
                    "reason": "Text appears before the first detected answer heading."
                })

        # ----------------------------------------------------
        # CASE 3: Process every heading on the page
        # ----------------------------------------------------

        for index, heading in enumerate(headings):

            answer_number = normalize_answer_number(
                heading.group(1)
            )

            # Content starts immediately after the heading.
            content_start = heading.end()

            # Content ends at the next answer heading.
            if index + 1 < len(headings):
                content_end = headings[index + 1].start()
            else:
                content_end = len(page_text)

            answer_text = page_text[
                content_start:content_end
            ].strip()

            current_answer_number = answer_number

            # Create the answer record only once.
            if answer_number not in answers:

                answers[answer_number] = {
                    "answer_number": answer_number,
                    "segments": []
                }

            print(
                f"  Page {page_number}: "
                f"Answer {answer_number} detected"
            )

            answers[answer_number]["segments"].append({
                "page": page_number,
                "page_name": page_name,
                "text": answer_text,
                "type": "answer_heading"
            })

    # ========================================================
    # BUILD FINAL ANSWER RECORDS
    # ========================================================

    final_answers = []

    for answer_number, answer_data in answers.items():

        segments = answer_data["segments"]

        # Combine segments in their original page order.
        combined_text = "\n\n".join(
            segment["text"]
            for segment in segments
            if segment["text"].strip()
        )

        pages = sorted(set(
            segment["page"]
            for segment in segments
            if segment["page"] is not None
        ))

        final_answers.append({
            "answer_number": answer_number,
            "pages": pages,
            "attempted": bool(combined_text.strip()),
            "text": combined_text,
            "segments": segments
        })

    return {
        "answers": final_answers,
        "unassigned_passages": unassigned_passages,
        "summary": {
            "total_answers_detected": len(final_answers),
            "total_unassigned_passages": len(unassigned_passages),
            "total_pages_processed": len(page_results)
        }
    }


# ============================================================
# MAIN FUNCTION
# ============================================================

def run_answer_grouping(
    input_path=DEFAULT_INPUT,
    output_path=DEFAULT_OUTPUT
):
    """Run question-wise grouping on the final OCR output."""

    print("=" * 60)
    print("EVALAI ANSWER GROUPING")
    print("=" * 60)

    page_results = load_ocr_output(input_path)

    print(f"\nTotal OCR pages: {len(page_results)}")

    grouped_output = group_answers(page_results)

    save_json(
        grouped_output,
        output_path
    )

    print("\n" + "=" * 60)
    print("ANSWER GROUPING COMPLETED")
    print("=" * 60)

    print(
        "Total answers detected:",
        grouped_output["summary"]["total_answers_detected"]
    )

    print(
        "Unassigned passages:",
        grouped_output["summary"]["total_unassigned_passages"]
    )

    print("\nDetected answers:")

    for answer in grouped_output["answers"]:
        print(
            f"Answer {answer['answer_number']} "
            f"| Pages: {answer['pages']}"
        )

    print("\nUnassigned passages:")

    for passage in grouped_output["unassigned_passages"]:
        print(
            f"Page {passage['page']} "
            f"| {passage['text'][:150]}"
        )

    print(f"\nOutput saved to: {output_path}")

    return grouped_output


# ============================================================
# COMMAND LINE EXECUTION
# ============================================================

if __name__ == "__main__":

    parser = argparse.ArgumentParser(
        description="Group OCR text into question-wise answers."
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=DEFAULT_INPUT,
        help="Path to final_ocr_output.json"
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Path to save grouped_answers.json"
    )

    args = parser.parse_args()

    run_answer_grouping(
        input_path=args.input,
        output_path=args.output
    )
